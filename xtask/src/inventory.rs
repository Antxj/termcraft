//! Generate parity inventories (markdown) from the reference app.

use crate::Reference;
use crate::dfm::{Object, Value, shortcut_label};
use anyhow::Result;
use std::fmt::Write as _;
use std::path::Path;

pub fn write_all(r: &Reference, out: &Path) -> Result<()> {
    std::fs::create_dir_all(out.join("forms"))?;
    let session_types = session_types(r);
    let menus = menus(r);
    let toolbar = toolbar(r);
    let components = components(r);
    std::fs::write(out.join("session-types.md"), &session_types)?;
    std::fs::write(out.join("menus.md"), &menus)?;
    std::fs::write(out.join("toolbar.md"), &toolbar)?;
    std::fs::write(out.join("components.md"), &components)?;

    let mut index = String::new();
    let _ = writeln!(index, "# Reference inventory — MobaXterm {}\n", r.version);
    index.push_str(
        "Generated by `cargo xtask inventory` from static inspection of the portable \
         build (no execution). Do not edit by hand.\n\n",
    );
    index.push_str("- [Session types and parameters](session-types.md)\n");
    index.push_str("- [Menus and shortcuts](menus.md)\n");
    index.push_str("- [Main toolbar](toolbar.md)\n");
    index.push_str("- [Bundled components](components.md)\n\n");
    index.push_str("## Forms\n\n| Form | Caption | Size | Controls |\n|---|---|---|---|\n");
    for (name, form) in &r.forms {
        let file = format!("forms/{name}.md");
        std::fs::write(out.join(&file), form_outline(name, form))?;
        let mut count = 0;
        form.walk(&mut |_, _| count += 1);
        let size = match (int(form, "ClientWidth"), int(form, "ClientHeight")) {
            (Some(w), Some(h)) => format!("{w}×{h}"),
            _ => String::new(),
        };
        let _ = writeln!(
            index,
            "| [{name}]({file}) | {} | {size} | {count} |",
            md(form.str_prop("Caption").unwrap_or(""))
        );
    }
    std::fs::write(out.join("README.md"), index)?;
    Ok(())
}

fn int(o: &Object, key: &str) -> Option<i64> {
    o.prop(key).and_then(Value::as_int)
}

/// Escape for a markdown table cell; Delphi line breaks become ` / `.
fn md(s: &str) -> String {
    s.replace('|', "\\|")
        .replace("\r\n", " / ")
        .replace(['\r', '\n'], " / ")
        .trim()
        .to_string()
}

/// Human-facing labels of a control.
fn labels(o: &Object) -> Vec<String> {
    let mut out = Vec::new();
    for key in ["Caption", "BoundLabel.Caption", "Text", "TextHint", "Hint"] {
        if let Some(s) = o.str_prop(key)
            && !s.trim().is_empty()
            && s != o.name
        {
            let tag = if key == "Caption" { "" } else { key };
            out.push(if tag.is_empty() {
                format!("\"{}\"", md(s))
            } else {
                format!("{tag}: \"{}\"", md(s))
            });
        }
    }
    if let Some(Value::List(items)) = o.prop("Items.Strings") {
        let items: Vec<String> = items.iter().filter_map(Value::as_str).map(md).collect();
        if !items.is_empty() {
            out.push(format!("items: [{}]", items.join(", ")));
        }
    }
    if let Some(Value::Collection(cols)) = o.prop("Columns") {
        let names: Vec<String> = cols
            .iter()
            .filter_map(|props| props.iter().find(|(k, _)| k == "Caption"))
            .filter_map(|(_, v)| v.as_str())
            .map(md)
            .collect();
        if !names.is_empty() {
            out.push(format!("columns: [{}]", names.join(", ")));
        }
    }
    if let Some(sc) = int(o, "ShortCut") {
        out.push(format!("⌨ {}", shortcut_label(sc)));
    }
    if matches!(o.prop("Visible"), Some(Value::Bool(false))) {
        out.push("(hidden)".into());
    }
    out
}

const NOISE: &[&str] = &[
    "TsAlphaImageList",
    "TImageList",
    "TTimer",
    "TsSkinProvider",
    "TsSkinManager",
    "TsHintManager",
    "TApplicationEvents",
    "TShape",
];

fn form_outline(name: &str, form: &Object) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# {name} — {}\n",
        md(form.str_prop("Caption").unwrap_or(""))
    );
    if let (Some(w), Some(h)) = (int(form, "ClientWidth"), int(form, "ClientHeight")) {
        let _ = writeln!(out, "Client size: {w}×{h}\n");
    }
    out.push_str("```text\n");
    form.walk(&mut |o, depth| {
        if depth == 0 || NOISE.contains(&o.class.as_str()) {
            return;
        }
        let pos = match (
            int(o, "Left"),
            int(o, "Top"),
            int(o, "Width"),
            int(o, "Height"),
        ) {
            (Some(l), Some(t), Some(w), Some(h)) => format!(" @{l},{t} {w}×{h}"),
            _ => String::new(),
        };
        let _ = writeln!(
            out,
            "{}{} {}{pos} {}",
            "  ".repeat(depth - 1),
            o.class,
            o.name,
            labels(o).join(" ")
        );
    });
    out.push_str("```\n");
    out
}

fn menus(r: &Reference) -> String {
    let mut out = String::from(
        "# Menus and shortcuts\n\nAll `TMainMenu` / `TPopupMenu` trees in every form.\n",
    );
    for (form_name, form) in &r.forms {
        form.walk(&mut |o, _| {
            if o.class != "TPopupMenu" && o.class != "TMainMenu" {
                return;
            }
            let _ = writeln!(out, "\n## {form_name} › {}\n", o.name);
            fn items(o: &Object, depth: usize, out: &mut String) {
                for c in o.children.iter().filter(|c| c.class == "TMenuItem") {
                    let cap = c.str_prop("Caption").unwrap_or("");
                    if cap == "-" {
                        let _ = writeln!(out, "{}- ---", "  ".repeat(depth));
                    } else {
                        let sc = int(c, "ShortCut")
                            .map(|s| format!(" `{}`", shortcut_label(s)))
                            .unwrap_or_default();
                        let hidden = if matches!(c.prop("Visible"), Some(Value::Bool(false))) {
                            " _(hidden)_"
                        } else {
                            ""
                        };
                        let label = if cap.is_empty() {
                            format!("_{}_", c.name)
                        } else {
                            md(&cap.replace('&', ""))
                        };
                        let _ = writeln!(out, "{}- {label}{sc}{hidden}", "  ".repeat(depth));
                    }
                    items(c, depth + 1, out);
                }
            }
            items(o, 0, &mut out);
        });
    }
    out
}

fn toolbar(r: &Reference) -> String {
    let mut out = String::from(
        "# Main window toolbar and quick buttons\n\n| Button | Caption | Hint |\n|---|---|---|\n",
    );
    if let Some(form) = r.forms.get("TFORMXTERM") {
        form.walk(&mut |o, _| {
            if o.class == "TsSpeedButton"
                && o.name.starts_with("Btn")
                && let Some(cap) = o.str_prop("Caption")
            {
                let _ = writeln!(
                    out,
                    "| {} | {} | {} |",
                    o.name,
                    md(cap),
                    md(o.str_prop("Hint").unwrap_or(""))
                );
            }
        });
    }
    out
}

/// Minimal ordered INI reader for SEPARAMS.
pub fn ini(text: &str) -> Vec<(String, Vec<(String, String)>)> {
    let mut out: Vec<(String, Vec<(String, String)>)> = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if let Some(sec) = line.strip_prefix('[').and_then(|l| l.strip_suffix(']')) {
            out.push((sec.to_string(), Vec::new()));
        } else if let Some((k, v)) = line.split_once('=')
            && let Some((_, kv)) = out.last_mut()
        {
            kv.push((k.to_string(), v.to_string()));
        }
    }
    out
}

fn session_types(r: &Reference) -> String {
    let mut out = String::from(
        "# Session types and parameters\n\n\
         Source: embedded `SEPARAMS` table. A parameter id `A_B` addresses a saved\n\
         bookmark value: split the value on `#` and take part **A** (1-based), then\n\
         split that on `%` and take field **B** (1-based). Example `3_2` (host) in\n\
         `#109#0%host%22%user…`: part 3 = `0%host%22%user…`, field 2 = `host`.\n\n\
         Part 2 is the bookmark **icon**; field `3_1` is the **session type index**\n\
         (the `N` in section `[1_N]`).\n",
    );
    let Some(raw) = r.files.get("SEPARAMS") else {
        out.push_str("\n_SEPARAMS not found._\n");
        return out;
    };
    let text = String::from_utf8_lossy(raw);
    for (section, kv) in ini(&text) {
        let get = |k: &str| kv.iter().find(|(key, _)| key == k).map(|(_, v)| v.as_str());
        let name = get("SectionName").unwrap_or("?");
        let icon = get("SectionIcon").unwrap_or("");
        let type_index = section
            .strip_prefix("1_")
            .map(|n| format!(" — type index `{n}`"))
            .unwrap_or_default();
        let _ = writeln!(out, "\n## {name} `[{section}]` icon `{icon}`{type_index}\n");
        out.push_str("| Id | Parameter | Default | Values | Level | UI component |\n|---|---|---|---|---|---|\n");
        for (k, caption) in &kv {
            let Some(id) = k.strip_prefix("Caption_") else {
                continue;
            };
            let f = |p: &str| get(&format!("{p}_{id}")).unwrap_or("").to_string();
            let _ = writeln!(
                out,
                "| `{id}` | {} | `{}` | `{}` | {} | {} |",
                md(caption),
                f("DfltVal"),
                f("AvailVals"),
                f("ParmLev"),
                f("Comp")
            );
        }
    }
    out
}

fn components(r: &Reference) -> String {
    let mut out = String::from("# Bundled third-party components\n\n## License files shipped\n\n");
    if let Some(zip) = r.files.get("LI")
        && let Ok(archive) = zip::ZipArchive::new(std::io::Cursor::new(zip.as_slice()))
    {
        let mut names: Vec<String> = archive
            .file_names()
            .filter_map(|n| n.ok().map(|n| n.into_owned()))
            .collect();
        names.sort();
        for n in names {
            let _ = writeln!(out, "- `{n}`");
        }
    }
    out.push_str("\n## Changelog lines mentioning embedded components\n\n");
    if let Some(log) = r.files.get("CHANGELOG") {
        for line in String::from_utf8_lossy(log).lines() {
            if line.contains("embedded") || line.contains("updated the") {
                let _ = writeln!(out, "{}", line.trim());
            }
        }
    }
    out
}
