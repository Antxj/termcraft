//! Generate `crates/tc-core/src/schema_gen.rs`: the session parameter schema
//! (sections, labels, defaults, value domains, widget kinds, combo items),
//! from the reference `SEPARAMS` table joined with the forms that host each
//! parameter's control.

use crate::Reference;
use crate::dfm::{Object, Value};
use anyhow::{Context as _, Result};
use std::fmt::Write as _;

/// Form instance prefixes used in `Comp_*` entries → form resource name.
const FORM_PREFIXES: &[(&str, &str)] = &[
    ("FormExpertSSH", "TFORMSSHPROTOSETTINGS"),
    ("FormFont", "TFORMFONTSELECTOR"),
    ("FormColor", "TFORMCOLORSSELECTOR"),
];
const EDITOR_FORM: &str = "TFORMSESSIONEDIT";

/// TermCraft defaults that intentionally differ from the reference
/// (section, parameter id, default). The reference font is proprietary.
const DEFAULT_OVERRIDES: &[(&str, &str, &str)] = &[("2", "4_1", "")];

fn find<'a>(form: &'a Object, name: &str) -> Option<&'a Object> {
    let mut hit = None;
    form.walk(&mut |o, _| {
        if hit.is_none() && o.name == name {
            hit = Some(o);
        }
    });
    hit
}

fn control<'a>(r: &'a Reference, comp: &str) -> Option<&'a Object> {
    if comp.is_empty() {
        return None;
    }
    if let Some((prefix, name)) = comp.split_once('.') {
        let form = FORM_PREFIXES
            .iter()
            .find(|(p, _)| *p == prefix)
            .and_then(|(_, f)| r.forms.get(*f))?;
        return find(form, name);
    }
    find(r.forms.get(EDITOR_FORM)?, comp)
}

fn items(o: &Object) -> Vec<String> {
    match o.prop("Items.Strings") {
        Some(Value::List(v)) => v
            .iter()
            .filter_map(Value::as_str)
            .map(String::from)
            .collect(),
        _ => Vec::new(),
    }
}

/// Rust expression for the widget of a parameter.
fn widget(ctrl: Option<&Object>, values: &str) -> String {
    let Some(o) = ctrl else {
        return "Widget::Text".into();
    };
    // `<deccol>`, `<MacroName>`… are typed values even when the reference
    // control is a checkbox that merely enables them.
    if values.starts_with('<') && !matches!(o.class.as_str(), "TsFilenameEdit" | "TsDirectoryEdit")
    {
        return "Widget::Text".into();
    }
    match o.class.as_str() {
        "TsCheckBox" | "TsRadioButton" | "TCheckBox" => "Widget::Check".into(),
        "TsSpinEdit" | "TsDecimalSpinEdit" => "Widget::Number".into(),
        "TsFilenameEdit" => "Widget::File".into(),
        "TsDirectoryEdit" => "Widget::Folder".into(),
        "TsComboBox" | "TsComboBoxEx" if values.contains("..") => {
            let items = items(o);
            if items.is_empty() {
                "Widget::Text".into()
            } else {
                let list: Vec<String> = items.iter().map(|s| format!("{s:?}")).collect();
                format!("Widget::Choice(&[{}])", list.join(", "))
            }
        }
        _ => "Widget::Text".into(),
    }
}

pub fn generate(r: &Reference) -> Result<String> {
    let raw = r
        .files
        .get("SEPARAMS")
        .context("SEPARAMS resource missing")?;
    let text = String::from_utf8_lossy(raw);
    let sections = crate::inventory::ini(&text);

    let mut out = String::new();
    let _ = writeln!(
        out,
        "// @generated by `cargo xtask schema` from the reference app {} — do not edit.\n\
         // Labels and value domains of session parameters (see docs/inventory/session-types.md).\n\n\
         use crate::schema::{{Param, Section, Widget}};\n\n\
         pub(crate) const SECTIONS: &[Section] = &[",
        r.version
    );
    let mut count = 0;
    for (key, kv) in &sections {
        let get = |k: &str| {
            kv.iter()
                .find(|(key, _)| key == k)
                .map_or("", |(_, v)| v.as_str())
        };
        let _ = writeln!(
            out,
            "    Section {{\n        key: {key:?},\n        name: {:?},\n        params: &[",
            get("SectionName")
        );
        for (k, label) in kv {
            let Some(id) = k.strip_prefix("Caption_") else {
                continue;
            };
            let f = |p: &str| get(&format!("{p}_{id}")).to_string();
            let values = f("AvailVals");
            let ctrl = control(r, &f("Comp"));
            let default = DEFAULT_OVERRIDES
                .iter()
                .find(|(s, i, _)| s == key && *i == id)
                .map_or_else(|| f("DfltVal"), |(_, _, d)| (*d).to_string());
            let _ = writeln!(
                out,
                "            Param {{ id: {id:?}, label: {label:?}, default: {:?}, values: {values:?}, basic: {}, widget: {} }},",
                default,
                f("ParmLev") == "1",
                widget(ctrl, &values),
            );
            count += 1;
        }
        out.push_str("        ],\n    },\n");
    }
    out.push_str("];\n");
    eprintln!("schema: {} sections, {count} parameters", sections.len());
    Ok(out)
}
